def tour_template() -> Template:
    blocks = [
        Block(BLOCK_MARKDOWN, _WELCOME, role="explain"),
        Block(BLOCK_MARKDOWN, _FIRST, role="task"),
        Block(BLOCK_CODE, _FIRST_CODE),
        Block(BLOCK_MARKDOWN, _SELECTION, role="hint"),
        Block(BLOCK_MARKDOWN, _LINES, role="task"),
        Block(BLOCK_CODE, _LINES_CODE),
        Block(BLOCK_MARKDOWN, _STEPS, role="task"),
        Block(BLOCK_CODE, STEPS_SAMPLE_CODE, steps=list(STEPS_SAMPLE_STEPS)),
        Block(BLOCK_MARKDOWN, _HUMAN, role="explain"),
        Block(BLOCK_CODE, _HUMAN_CODE, lang="javascript"),
        Block(BLOCK_MARKDOWN, _COMMENTS, role="explain"),
        Block(BLOCK_CODE, _COMMENTS_CODE),
        Block(BLOCK_MARKDOWN, _PROFILE, role="hint"),
        Block(BLOCK_MARKDOWN, _OWN, role="text"),
    ]
    t = Template(title=TOUR_TITLE, blocks=blocks)
    t.active_block = blocks[2].id    # первый блок кода — сразу можно нажать Ctrl+F9
    return t
